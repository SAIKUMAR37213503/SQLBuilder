// The contract between the app and a database engine. The SQL Lab only talks
// to an engine through a client (client.js), which sends these operations to
// the engine adapter (sqlite-adapter.js) inside the database worker:
//
//   info()                         engine name/version, persistence, open db
//   create(id), open(id), close(), remove(id), removeAll(), duplicate(from, to)
//   execute(sql, { pageSize })     { results: StatementResult[], error, inTransaction }
//   fetchPage(cursor, { pageSize }), closeCursor(cursor)
//   schema()                       tables and views of the open database
//   exportFile(id), importFile(id, bytes)
//
// A StatementResult is { sql, kind, columns, rows, more, cursor, rowsAffected,
// durationMs, statement, start }. rowsAffected is null unless the engine
// reported it; durationMs is measured by the engine around that statement.

/** An error the engine reports, with what's known about where it happened. */
export class DatabaseError extends Error {
    /**
     * @param {string} message
     * @param {{ code?: string, line?: number, column?: number, statement?: number }} [details]
     */
    constructor(message, details = {}) {
        super(message);
        this.name = 'DatabaseError';
        this.code = details.code || 'ERROR';
        if (details.line !== undefined) this.line = details.line;
        if (details.column !== undefined) this.column = details.column;
        if (details.statement !== undefined) this.statement = details.statement;
    }
}

/**
 * The 1-based line and column of a byte offset in UTF-8 text.
 * @param {Uint8Array} bytes
 * @param {number} offset
 */
export function positionAt(bytes, offset) {
    const before = new TextDecoder().decode(bytes.subarray(0, Math.max(0, Math.min(bytes.length, offset))));
    const lines = before.split('\n');
    return { line: lines.length, column: [...lines[lines.length - 1]].length + 1 };
}

/** What a database file is called in storage. */
export const databaseFileName = (/** @type {string} */ id) => `db-${id}.sqlite3`;

/** Ids are generated by the app; anything else is refused before reaching storage. */
export const isDatabaseId = (/** @type {unknown} */ id) => typeof id === 'string' && /^[a-z0-9][a-z0-9-]{3,39}$/.test(id);
